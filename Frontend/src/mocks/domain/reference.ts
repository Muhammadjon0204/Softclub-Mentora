/**
 * Единая точка отсчёта времени для всех детерминированных mock-данных.
 *
 * Фиксированная дата — намеренно: если бы генератор использовал `Date.now()`
 * в момент построения сидов, один и тот же код давал бы разные «просроченные»/
 * «активные» распределения статусов в зависимости от того, когда его запустили,
 * а тесты стали бы недетерминированными. Форматирование относительного времени
 * («2 часа назад») по-прежнему считается от реального `Date.now()` на рендере —
 * это чистая функция от уже сохранённого абсолютного timestamp, не источник
 * недетерминированности.
 */
export const MOCK_NOW = Date.parse('2026-08-02T09:00:00.000Z');

export const MINUTE_MS = 60 * 1000;
export const HOUR_MS = 60 * MINUTE_MS;
export const DAY_MS = 24 * HOUR_MS;
