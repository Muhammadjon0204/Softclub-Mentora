using MentorTaskFlow.Api.Authorization;
using MentorTaskFlow.Application.Common.Abstractions;
using MentorTaskFlow.Application.Common.Tenancy;
using MentorTaskFlow.Contracts.Users;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace MentorTaskFlow.Api.Controllers;

/// <summary>Profile photos: the directory of who has one, and the photos themselves.</summary>
[ApiController]
public sealed class AvatarsController(IAvatarService avatars, ICurrentUserAccessor currentUser) : ControllerBase
{
    /// <summary>
    /// <c>GET /users/avatars</c> — every photo in the caller's organization, by user id.
    /// </summary>
    [HttpGet("api/v1/users/avatars")]
    [Authorize(Policy = MtfPolicies.Authenticated)]
    [ProducesResponseType<IReadOnlyList<UserAvatarDto>>(StatusCodes.Status200OK)]
    public async Task<ActionResult<IReadOnlyList<UserAvatarDto>>> ListAsync(CancellationToken cancellationToken)
    {
        var user = currentUser.Current
            ?? throw new Application.Common.Exceptions.UnauthorizedException();

        Response.Headers.CacheControl = "private, no-cache";
        return Ok(await avatars.ListAsync(user.OrganizationId, cancellationToken));
    }

    /// <summary>
    /// <c>GET /avatars/{fileName}</c> — the photo itself.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Anonymous on purpose: an <c>&lt;img&gt;</c> cannot send the in-memory access token. The name is
    /// 128 random bits generated by the server, so it is as hard to guess as a presigned link — but,
    /// unlike one, it never changes, which is what lets the photo be cached for good.
    /// </para>
    /// <para>
    /// <c>immutable</c> is safe because a new photo always gets a new name; a removed one stops existing
    /// in storage and answers 404. <c>Cross-Origin-Resource-Policy</c> allows the web app, served from
    /// its own domain, to embed it.
    /// </para>
    /// </remarks>
    [HttpGet("api/v1/avatars/{fileName}")]
    [AllowAnonymous]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> GetAsync(string fileName, CancellationToken cancellationToken)
    {
        var avatar = await avatars.OpenAsync(fileName, cancellationToken);

        if (avatar is null)
        {
            return NotFound();
        }

        Response.Headers.CacheControl = "public, max-age=31536000, immutable";
        Response.Headers["Cross-Origin-Resource-Policy"] = "cross-origin";
        return File(avatar.Bytes, avatar.ContentType);
    }
}
