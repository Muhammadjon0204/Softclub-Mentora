export function auditTone(action: string, result: string): 'danger' | 'success' | 'brand' | 'neutral' {
  if (result !== 'Success' || action.includes('reject') || action.includes('reuse_detected') || action.endsWith('.deactivate')) return 'danger';
  if (action.endsWith('.create') || action.endsWith('.activate') || action.endsWith('.publish') || action.endsWith('.approve')) return 'success';
  return action.includes('update') || action.includes('change') ? 'brand' : 'neutral';
}
